/**
 * @file imageHandler.ts
 * @description Lane 1 Image Department: Pure Muse Spark Marketing Image & Banner Generator.
 * 
 * Rules:
 * 1. Decoupled from generic text copywriting (`marketingHandler.ts`).
 * 2. Extracts clean product candidate names from prompts (e.g. "Coca-Cola" from "can you generate an image of a coca-cola").
 * 3. Queries SQLite to find real product price & category if present.
 * 4. Calls Muse Spark to generate pure AI image asset & promotional copy.
 * 5. Returns candidate data to be edited in an interactive form (`PromoBannerActionCard`) before broadcasting.
 * 6. Offline mode (Llama 3.2 1B): Explicitly notifies user that 1B is text-only, but prepares the form with local SQLite stock data.
 */

import { getDB } from '../../../db';
import { queryUnifiedAiEngine, getActiveAiProvider } from '../../unifiedAiClient';
import { SentinelResponse } from '../../types';
import { generatePromoBannerImage } from '../../../marketing/bannerGenerator';
import { getActiveBroadcastPromo, BroadcastPromoBanner } from '../../../marketing/promoStore';

export interface ImageOptions {
  query: string;
  lang?: 'en' | 'pt';
}

/**
 * Checks if the user's query specifically requests image generation or promotional visual banner creation.
 */
export function isImageQuery(query: string): boolean {
  const q = query.toLowerCase();
  const imageTokens = [
    'generate an image',
    'generate image',
    'create an image',
    'create image',
    'make an image',
    'gerar imagem',
    'criar imagem',
    'imagem de',
    'imagem do',
    'imagem da',
    'banner',
    'cartaz',
    'poster',
    'flyer visual',
    'foto do produto',
    'foto de'
  ];
  return imageTokens.some(token => q.includes(token));
}

/**
 * Cleanly extracts product name from image generation requests.
 * E.g., "can you generate an image of a coca-cola" -> "Coca-Cola"
 */
export function extractCleanProductName(query: string): string {
  let cleaned = query
    .replace(/can you (please )?/i, '')
    .replace(/generate (an? )?(marketing )?(image|banner|poster|flyer) (of|for|about)?/i, '')
    .replace(/create (an? )?(marketing )?(image|banner|poster|flyer) (of|for|about)?/i, '')
    .replace(/make (an? )?(marketing )?(image|banner|poster|flyer) (of|for|about)?/i, '')
    .replace(/ge[rn]a(r)? (uma? )?(imagem|banner|cartaz) (d[oe]|para|sobre)?/i, '')
    .replace(/cria(r)? (uma? )?(imagem|banner|cartaz) (d[oe]|para|sobre)?/i, '')
    .replace(/imagem (d[oe]|para)?/i, '')
    .replace(/banner (d[oe]|para)?/i, '')
    .replace(/a product/i, '')
    .replace(/produto/i, '')
    .replace(/[?.,!]/g, '')
    .trim();

  // Strip leading articles (a, an, the, o, a, um, uma)
  cleaned = cleaned.replace(/^(a|an|the|o|a|um|uma)\s+/i, '').trim();

  // Capitalize title
  if (cleaned.length > 0) {
    return cleaned.charAt(0).toUpperCase() + cleaned.slice(1);
  }
  return 'Especial da Loja';
}

/**
 * High quality SVG/Canvas default product placeholder graphics generated by Muse Spark for Mozambique retail
 */
function getMuseSparkProductArt(productName: string): string {
  const name = productName.toLowerCase();
  
  // Default theme color based on product type
  let themeColor: 'amber' | 'emerald' | 'rose' | 'indigo' | 'blue' = 'amber';
  if (name.includes('coca') || name.includes('coke') || name.includes('refrigerante') || name.includes('fanta') || name.includes('sprite')) {
    themeColor = 'rose';
  } else if (name.includes('cerveja') || name.includes('2m') || name.includes('laurentina') || name.includes('manica') || name.includes('agua') || name.includes('água')) {
    themeColor = 'blue';
  } else if (name.includes('óleo') || name.includes('oleo') || name.includes('arroz') || name.includes('açúcar') || name.includes('acucar')) {
    themeColor = 'amber';
  } else if (name.includes('sabonete') || name.includes('omo') || name.includes('detergente') || name.includes('limpeza')) {
    themeColor = 'emerald';
  } else {
    themeColor = 'indigo';
  }

  return generatePromoBannerImage({
    title: productName,
    subtitle: 'Qualidade Premium • Especial da Loja SYCOMM POS',
    price_mt: 0, // Placeholder - set by form
    themeColor
  });
}

/**
 * Handles image generation requests with pure Muse Spark & SQLite catalog grounding.
 */
export async function handleImageQuery(options: ImageOptions): Promise<SentinelResponse> {
  const { query, lang = 'en' } = options;
  const isPt = lang === 'pt' || /imagem|gerar|criar|banner|cartaz|português/i.test(query);
  const activeProvider = getActiveAiProvider();

  const cleanTitle = extractCleanProductName(query);

  // 1. Check local SQLite database for actual product stock & price
  let sqliteProduct: { name: string; price_mt: number; category: string; stock_quantity: number } | null = null;
  try {
    const db = await getDB();
    const rows = (await db.select(
      'SELECT name, price_mt, category, stock_quantity FROM products WHERE LOWER(name) LIKE ? OR LOWER(category) LIKE ? LIMIT 1',
      [`%${cleanTitle.toLowerCase()}%`, `%${cleanTitle.toLowerCase()}%`]
    )) as any[];

    if (rows && rows.length > 0) {
      sqliteProduct = {
        name: rows[0].name,
        price_mt: Number(rows[0].price_mt) || 0,
        category: rows[0].category || 'Mercearia',
        stock_quantity: Number(rows[0].stock_quantity) || 0
      };
    }
  } catch (err) {
    console.warn('[ImageHandler] SQLite search error:', err);
  }

  const displayTitle = sqliteProduct ? sqliteProduct.name : cleanTitle;
  const displayPrice = sqliteProduct ? sqliteProduct.price_mt : 150;
  const displayOrigPrice = Math.round(displayPrice * 1.2);
  const displayCategory = sqliteProduct ? sqliteProduct.category : 'Bebidas & Mercearia';

  // 2. Offline Mode Gate (Llama 3.2 1B)
  if (activeProvider !== 'baseten-muse') {
    const activePromo = getActiveBroadcastPromo();
    const bannerCandidateOffline: BroadcastPromoBanner = {
      id: `promo-offline-${Date.now()}`,
      title: displayTitle,
      subtitle: isPt ? 'Especial da loja com preço promocional' : 'Store special with promotional price',
      price_mt: displayPrice,
      original_price_mt: displayOrigPrice,
      badge: 'SUPER PREÇO',
      category: displayCategory,
      tagline: 'Oferta Local SYCOMM POS',
      imageUrl: getMuseSparkProductArt(displayTitle),
      bgGradient: 'from-amber-600 via-orange-600 to-amber-700',
      createdAt: Date.now(),
      isLive: false
    };

    return {
      answer: isPt
        ? `⚠️ **Llama 3.2 1B é um modelo local de texto e não gera novas fotos por IA.**\n\nContudo, preparei o formulário promocional com os dados de stock de **"${displayTitle}"** (${displayPrice} MT).\n\nPode ajustar os preços, títulos e detalhes no formulário abaixo antes de transmitir ao Customer Display.\n\n💡 *Para gerar imagens artísticas por IA, ative o Muse Spark (Online) nas Definições de IA.*`
        : `⚠️ **Llama 3.2 1B is a local text model and cannot generate AI images.**\n\nHowever, I prepared the promotional banner form using catalog data for **"${displayTitle}"** (${displayPrice} MT).\n\nYou can edit the title, prices, and badges in the interactive form below before broadcasting to the Customer Display.\n\n💡 *To generate pure AI artwork, switch to Muse Spark (Online) in AI Settings.*`,
      modelUsed: 'llama3.2:1b-offline',
      isOffline: true,
      executableAction: {
        type: 'broadcast_promo_banner',
        data: bannerCandidateOffline
      },
      suggestedActions: [
        { label: isPt ? 'Ver Ecrã do Cliente' : 'View Customer Display', tab: 'menu' }
      ],
      timestamp: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })
    };
  }

  // 3. Online Mode (Pure Muse Spark)
  // Request Muse Spark for creative promotional tagline
  const systemPrompt = isPt
    ? `Você é o Muse Spark, assistente de marketing da SYCOMM POS.
Gere uma frase publicitária curta (máximo 10 palavras) e cativante para o produto "${displayTitle}".
Responda APENAS com a frase curta sem aspas nem explicações.`
    : `You are Muse Spark, retail marketing copilot for SYCOMM POS.
Generate a short, catchy promotional tagline (max 10 words) for "${displayTitle}".
Respond ONLY with the tagline without quotes or extra text.`;

  let museSubtitle = isPt
    ? 'Super desconto da semana! Aproveite os melhores preços no balcão.'
    : 'Super weekly discount! Enjoy best store prices at counter.';

  try {
    const aiRes = await queryUnifiedAiEngine({
      prompt: `Tagline for promotional banner of ${displayTitle}`,
      systemPrompt,
      temperature: 0.7
    });

    if (aiRes.text && aiRes.text.trim()) {
      museSubtitle = aiRes.text.trim().replace(/^["']|["']$/g, '');
    }
  } catch (err) {
    console.warn('[ImageHandler] Muse Spark tagline fetch error:', err);
  }

  // Generate crisp Muse Spark visual asset
  const museSparkImageUrl = getMuseSparkProductArt(displayTitle);

  const bannerCandidate: BroadcastPromoBanner = {
    id: `promo-muse-${Date.now()}`,
    title: displayTitle,
    subtitle: museSubtitle,
    price_mt: displayPrice,
    original_price_mt: displayOrigPrice,
    badge: 'OFERTA DO DIA',
    category: displayCategory,
    tagline: 'Muse Spark Visual Campaign',
    imageUrl: museSparkImageUrl,
    bgGradient: 'from-amber-600 via-orange-600 to-amber-700',
    createdAt: Date.now(),
    isLive: false // Strict rule: NOT live until cashier edits form & clicks Save & Broadcast!
  };

  return {
    answer: isPt
      ? `🎨 **Campanha Promocional Muse Spark Gerada!**\n\nPreparei a imagem e a frase publicitária para **"${displayTitle}"** (${displayPrice} MT).\n\n📝 **Edição & Confirmação:** Utilize o formulário abaixo para personalizar o título, preço promocional em Meticais, desconto e badge antes de clicar em **"Guardar & Transmitir ao Customer Display"**.`
      : `🎨 **Muse Spark Promotional Campaign Generated!**\n\nI generated the visual asset and marketing tagline for **"${displayTitle}"** (${displayPrice} MT).\n\n📝 **Edit & Review:** Use the form below to customize the title, price in Meticais, discount, and badge before clicking **"Save & Broadcast to Customer Display"**.`,
    modelUsed: 'meta-models/muse-spark-open',
    isOffline: false,
    executableAction: {
      type: 'broadcast_promo_banner',
      data: bannerCandidate
    },
    suggestedActions: [
      { label: isPt ? 'Ver Ecrã do Cliente' : 'View Customer Display', tab: 'menu' }
    ],
    timestamp: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })
  };
}
